"""Write docs/m0-results.md from recorded probe artifacts.

Reads: the newest phase a/b report in tools/m0_probe/results/ plus the live block assembled
from already-recorded live submissions. Performs no live task and no model call.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from render_results import render, rows_from_report  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[2]
RESULTS_DIR = REPO_ROOT / "tools" / "m0_probe" / "results"
LIVE_BLOCK = REPO_ROOT / ".probe" / "c" / "live-block.json"
OUT = REPO_ROOT / "docs" / "m0-results.md"

HEADER = """# M0 transport probe results

Generated by `tools/m0_probe/render_results.py` from recorded artifacts only - no live task
was re-run to produce this table. Rows are grouped by what actually produced the evidence:

* `documented` - what the upstream/installed package claims.
* `local_observation` - what a read-only local check showed on this machine.
* `mock` - `acpx -> mock ACP agent` (a mock replaces DSH, so this is **not** DSH evidence).
* `live` - `acpx -> real DSH ACP`; the experimental budget was 2 top-level submissions, and
  the recorded sequence used 3 attempts - one of which the budget counter correctly refused.
  That is a top-level task count, not an API-request count and not a billing figure.

An untested capability stays `not tested`; nothing is inferred from a neighbouring row.
"""


def main() -> int:
    reports = sorted(RESULTS_DIR.glob("probe-*.json"), key=lambda p: p.stat().st_mtime)
    if not reports:
        print("no phase a/b report found; run tools/m0_probe/run_probe.py --phase a --phase b")
        return 4
    ab = json.loads(reports[-1].read_text(encoding="utf-8"))
    live = json.loads(LIVE_BLOCK.read_text(encoding="utf-8")) if LIVE_BLOCK.exists() else None

    rows = rows_from_report({"capability_table": ab.get("capability_table", []), "c_live": live})
    table = render(rows)
    OUT.write_text(HEADER + "\n" + table + "\n", encoding="utf-8")
    print(table)
    print(f"\nwrote {OUT} (source: {reports[-1].name})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
